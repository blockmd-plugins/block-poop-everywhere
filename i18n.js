export function isEn(locale) {
  return String(locale || '').trim().toLowerCase().startsWith('en');
}

export function getStrings(locale) {
  return isEn(locale) ? STRINGS.en : STRINGS.zh;
}

export function formatMessage(template, vars = {}) {
  return String(template || '').replace(/\{([a-zA-Z0-9_]+)\}/g, (full, key) => (
    Object.prototype.hasOwnProperty.call(vars, key) ? String(vars[key]) : full
  ));
}

export function localizeError(message, locale) {
  const raw = String(message || '').trim();
  const t = getStrings(locale);
  if (isEn(locale) && CHINESE_RE.test(raw)) {
    return t.err_failed;
  }
  return raw || t.err_failed;
}
